// Phone readability check for every plate in every format. Usage: node check.js [ids...] [--report=reports/readability.md]
// Renders each plate at its native size and measures every piece of text, including diagram labels:
//   size      every word is at least the format's --floor; the lede and notes are at least --body
//   fit       no text is cut off by the plate, the diagram canvas or the box it sits in
//   contrast  every word has a WCAG contrast ratio of at least 4.5:1 against what is behind it
// It also reports how big the smallest word is on a 390 px wide phone (iPhone 12 to 16), the image shown at full width.
// Exits with code 1 if any check fails.
const { chromium } = require('playwright');
const path = require('path');
const fs = require('fs');

const args = process.argv.slice(2);
const ids = args.filter((a) => !a.startsWith('--'));
const reportArg = args.find((a) => a.startsWith('--report='));
const FORMATS = { '169': [1920, 1080, '16:9'], '45': [1080, 1350, '4:5'], '11': [1080, 1080, '1:1'] };
// The standard, in px at the image's native size: [any text, lede and notes]. Fixed here, not read from the CSS,
// so lowering the type in src/plate.css makes this check fail.
const FLOORS = { '169': [42, 48], '45': [30, 34], '11': [30, 34] };
const PHONE = 390;        // CSS px across a typical phone screen, held upright
const MIN_CONTRAST = 4.5; // WCAG 2.2 AA for normal text

(async () => {
  const browser = await chromium.launch();
  const rows = [];
  const failures = [];
  for (const [f, [w, h, label]] of Object.entries(FORMATS)) {
    const page = await browser.newPage({ viewport: { width: w, height: h } });
    for (let i = 1; i <= 11; i++) {
      const id = String(i).padStart(2, '0');
      if (ids.length && !ids.includes(id)) continue;
      await page.goto('file://' + path.join(__dirname, `plate.html?id=${id}&f=${f}`));
      await page.waitForSelector('body[data-ready="1"]');
      const r = await page.evaluate(measure, [MIN_CONTRAST, ...FLOORS[f]]);
      const phone = (px) => (px * PHONE / w).toFixed(1);
      rows.push({ id, f, label, ...r, phoneMin: phone(r.minSize), phoneBody: phone(r.minBody) });
      r.problems.forEach((p) => failures.push(`${id} ${label}: ${p}`));
    }
    await page.close();
  }
  await browser.close();

  const head = '| Plate | Format | Smallest text | Smallest lede/note | On a 390 px phone | Lowest contrast | Text runs checked | Result |\n|---|---|---|---|---|---|---|---|';
  const body = rows.map((r) => `| ${r.id} | ${r.label} | ${r.minSize.toFixed(1)} px (floor ${r.floor}) | ${r.minBody.toFixed(1)} px (floor ${r.body}) | ${r.phoneMin} px / ${r.phoneBody} px | ${r.minContrast.toFixed(2)}:1 | ${r.count} | ${r.problems.length ? 'FAIL' : 'pass'} |`).join('\n');
  console.log(head + '\n' + body);
  if (failures.length) { console.log('\nFAILURES\n' + failures.join('\n')); }
  else console.log(`\nAll ${rows.length} images pass: size floors, fit and contrast.`);

  if (reportArg) {
    const out = path.resolve(__dirname, reportArg.split('=')[1]);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    const worst = (f) => rows.filter((r) => r.f === f).reduce((a, r) => Math.min(a, r.minSize), Infinity);
    const md = `# Phone readability report\n\nGenerated by \`node check.js --report=reports/readability.md\`. Every word on every image is measured in the rendered plate, diagram labels included.\n\n` +
      `| Format | Image width | Floor for any text | Floor for lede and notes | Smallest text found | Smallest text on a 390 px phone, image at full width |\n|---|---|---|---|---|---|\n` +
      Object.entries(FORMATS).map(([f, [w, , l]]) => { const r = rows.find((x) => x.f === f); return r ? `| ${l} | ${w} px | ${r.floor} px | ${r.body} px | ${worst(f).toFixed(1)} px | ${(worst(f) * PHONE / w).toFixed(1)} px |` : ''; }).join('\n') +
      `\n\nThe 16:9 image is the landscape format for slides, websites and video. On a phone held sideways it fills the screen height (390 px), so its smallest text is ${(worst('169') * PHONE / 1080).toFixed(1)} px there.` +
      `\n\nRules checked on each image: every word at or above the floor, no text cut off by the plate, the diagram or its box, and a WCAG contrast ratio of at least ${MIN_CONTRAST}:1 for every word.\n\n` +
      `## Every image\n\n${head}\n${body}\n\n${failures.length ? '## Failures\n\n' + failures.map((x) => '- ' + x).join('\n') : `All ${rows.length} images pass.`}\n`;
    fs.writeFileSync(out, md);
    console.log('Report written to ' + path.relative(__dirname, out));
  }
  process.exit(failures.length ? 1 : 0);
})();

// Runs inside the page. Returns sizes, contrast and any problems for one plate.
function measure([contrastFloor, floor, body]) {
  const plate = document.querySelector('.plate');
  const cs = getComputedStyle(plate);
  const P = plate.getBoundingClientRect();
  const problems = [];
  let minSize = Infinity, minBody = Infinity, minContrast = Infinity, count = 0;

  const rgb = (s) => {
    if (!s || s === 'none' || s === 'transparent') return null;
    if (s[0] === '#') { const n = s.length === 4 ? s.slice(1).split('').map((c) => c + c).join('') : s.slice(1); return [0, 2, 4].map((k) => parseInt(n.slice(k, k + 2), 16)); }
    const m = s.match(/rgba?\(([^)]+)\)/); if (!m) return null;
    const v = m[1].split(/[ ,/]+/).filter(Boolean).map(Number); if (v.length > 3 && v[3] === 0) return null; return v.slice(0, 3);
  };
  const lum = (c) => { const [r, g, b] = c.map((v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); }); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
  const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
  const well = rgb(cs.getPropertyValue('--well').trim());
  const inside = (a, b, m = 0) => a.left >= b.left - m && a.right <= b.right + m && a.top >= b.top - m && a.bottom <= b.bottom + m;
  const short = (t) => JSON.stringify(t.length > 34 ? t.slice(0, 32) + '…' : t);

  function check(text, size, minFor, fg, bg, rect, extra) {
    count++;
    minSize = Math.min(minSize, size);
    if (minFor === body) minBody = Math.min(minBody, size);
    if (size < minFor - 0.05) problems.push(`${short(text)} is ${size.toFixed(1)} px, below ${minFor} px`);
    if (!inside(rect, P, 0.5)) problems.push(`${short(text)} runs outside the image`);
    if (extra) problems.push(extra);
    if (fg && bg) {
      const c = ratio(fg, bg); minContrast = Math.min(minContrast, c);
      if (c < contrastFloor) problems.push(`${short(text)} contrast ${c.toFixed(2)}:1, below ${contrastFloor}:1`);
    }
  }

  // HTML text: titles, lede, notes, meta, sources
  const walker = document.createTreeWalker(plate, NodeFilter.SHOW_TEXT);
  let n;
  while ((n = walker.nextNode())) {
    const t = n.textContent.trim(); const el = n.parentElement;
    if (!t || el.closest('svg')) continue;
    const st = getComputedStyle(el);
    let bg = null;
    for (let a = el; a && !bg; a = a.parentElement) bg = a.classList.contains('fig') ? well : rgb(getComputedStyle(a).backgroundColor);
    const range = document.createRange(); range.selectNodeContents(n);
    const minFor = el.closest('.lede, .notes') && !el.closest('.n') ? body : floor;
    check(t, parseFloat(st.fontSize), minFor, rgb(st.color), bg || rgb(cs.backgroundColor), range.getBoundingClientRect());
  }
  // HTML containers that clip their content
  plate.querySelectorAll('.head, .notes, .src, .meta, .fig').forEach((e) => {
    if (e.scrollHeight > e.clientHeight + 2) problems.push(`.${e.className} overflows its area`);
  });

  // diagram labels: rendered size = font-size x the canvas scale
  const svg = plate.querySelector('.fig svg');
  const S = svg.getBoundingClientRect();
  svg.querySelectorAll('text').forEach((tx) => {
    const t = tx.textContent; const m = tx.getScreenCTM();
    const size = parseFloat(tx.getAttribute('font-size')) * Math.hypot(m.a, m.b);
    const R = tx.getBoundingClientRect();
    // what is painted behind the label: the topmost filled shape under its centre
    let bgEl = null, extra = '';
    for (const e of document.elementsFromPoint(R.left + R.width / 2, R.top + R.height / 2)) {
      if (e === tx || tx.contains(e) || e.closest('text')) continue;
      if (!(e instanceof SVGGeometryElement) || !svg.contains(e)) continue;
      if (!rgb(getComputedStyle(e).fill)) continue;
      bgEl = e; break;
    }
    if (!inside(R, S, 1)) extra = `${short(t)} runs outside the diagram`;
    else if (bgEl && bgEl.tagName === 'rect' && !inside(R, bgEl.getBoundingClientRect(), 1)) extra = `${short(t)} runs outside its box`;
    check(t, size, floor, rgb(tx.getAttribute('fill')), bgEl ? rgb(getComputedStyle(bgEl).fill) : well, R, extra);
  });
  return { floor, body, minSize, minBody, minContrast, count, problems };
}
